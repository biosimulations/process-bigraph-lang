/**
 * A model header from the JSON `describe-model` writes (`pblang-model/0`): the model's time unit and its
 * compartments, species and parameters as typed, unit-carrying values, plus the counts and SBML facts a solver
 * cares about in `meta`. The Python side reads the model file; this side renders the `.pbl` declaration.
 */
import type { ConfigField, ModelDecl } from "./headers.js";
import type { Named } from "./types.js";

interface Quantity {
  value?: number | bigint | null;
  initial?: number | bigint | null;
  units?: string | null;
  kind?: string;
}

export interface ModelHeaderJson {
  name: string;
  source: string;
  sbml?: {
    id?: string | null;
    level?: number | bigint | null;
    version?: number | bigint | null;
    packages?: string[];
  };
  time_units?: string | null;
  compartments?: Record<string, Quantity>;
  species?: Record<string, Quantity>;
  parameters?: Record<string, Quantity>;
  counts?: Record<string, number | bigint>;
  notes?: string[];
}

export function modelDeclFromHeader(header: ModelHeaderJson): ModelDecl {
  const typed = (
    q: Quantity,
    value: number | bigint | null | undefined,
  ): ConfigField => {
    const type: Named = { kind: "named", name: "float", args: [] };
    if (q.units != null) type.units = q.units;
    const field: ConfigField = { type, hasDefault: value != null };
    if (value != null)
      field.default = typeof value === "bigint" ? Number(value) : value;
    return field;
  };
  const decl: ModelDecl = {
    name: header.name,
    source: header.source,
    blocks: { compartments: {}, species: {}, parameters: {} },
    openBlocks: new Set(),
    meta: {},
    notes: [...(header.notes ?? [])],
    isSort: false,
  };
  if (header.time_units != null) decl.timeUnits = header.time_units;
  for (const [k, q] of Object.entries(header.compartments ?? {}))
    decl.blocks.compartments[k] = typed(q, q.value);
  for (const [k, q] of Object.entries(header.species ?? {}))
    decl.blocks.species[k] = typed(q, q.initial);
  for (const [k, q] of Object.entries(header.parameters ?? {}))
    decl.blocks.parameters[k] = typed(q, q.value);
  const kinds = new Set(Object.values(header.species ?? {}).map((s) => s.kind));
  if (kinds.size > 1)
    for (const [k, s] of Object.entries(header.species ?? {}))
      decl.notes.push(`species ${k}: ${s.kind}`);
  const sbml = header.sbml ?? {};
  decl.meta.sbml =
    sbml.level != null ? `L${sbml.level}V${sbml.version}` : "unknown";
  if (sbml.id && sbml.id !== header.name) decl.meta.sbml_id = sbml.id;
  if (kinds.size === 1) decl.meta.kind = [...kinds][0];
  for (const [k, v] of Object.entries(header.counts ?? {}))
    decl.meta[k] = typeof v === "number" ? BigInt(v) : v;
  if (sbml.packages && sbml.packages.length > 0)
    decl.meta.packages = [...sbml.packages];
  return decl;
}

/** The header comment of a generated model file. */
export function modelHeaderLead(header: ModelHeaderJson): string {
  const sbml = header.sbml ?? {};
  const version =
    sbml.level != null ? `L${sbml.level}V${sbml.version}` : "unknown level";
  return `// pblang v2 model header - generated by describe-model from ${header.source} (SBML ${version})\n`;
}
