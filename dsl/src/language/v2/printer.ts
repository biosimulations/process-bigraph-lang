/**
 * The v2 model -> canonical `.pbl` text (the last half of `decompile`).
 *
 * The printer is deterministic: it orders stores, then nodes, then edges (each in source order), prints a block
 * inline when it fits in `width` columns and one entry per line otherwise, and externalizes large arrays and
 * texts into sidecar assets (`array(file("…"))`, `file("…")`) so the text stays reviewable. Its output is a
 * fixpoint: parsing it and printing again yields the same text.
 */
import { floatLiteral, pyFloatRepr, pyJsonString, wrapText } from "./format.js";
import {
  type ConfigField,
  type InterfaceDecl,
  type ModelDecl,
  type Registry,
} from "./headers.js";
import {
  type Address,
  addressShortName,
  addressText,
  type Composite,
  type Dict,
  type Document,
  type Edge,
  edgeIsComposite,
  type Element,
  elementCount,
  type Emitter,
  type ExternalRef,
  type Face,
  isDict,
  isExternalRef,
  isIdentifier,
  isModelRef,
  isNdArray,
  isParamRef,
  isSite,
  isSiteDict,
  isTuple,
  MISSING,
  MODEL_BLOCKS,
  type Node,
  type Param,
  type ParamRef,
  type Site,
  type Store,
  type Wire,
} from "./model.js";
import { pathFromDocument, pathToText, wireFromDocument } from "./paths.js";
import { parseType, surface, type Named, type TypeExpr } from "./types.js";

export const EMITTER_ALIASES: Record<string, string> = {
  RAMEmitter: "ram",
  ParquetEmitter: "parquet",
  SQLiteEmitter: "sqlite",
  XarrayEmitter: "xarray",
  ConsoleEmitter: "console",
  JSONEmitter: "json",
};
const INDENT = "  ";

export interface Printed {
  text: string;
  /** sidecar assets by path, as text (JSON or raw) */
  assets: Map<string, string>;
}

export interface PrintOptions {
  name?: string;
  registry?: Registry;
  width?: number;
  maxElements?: number;
  maxText?: number;
}

/**
 * Print a module. `name` names the source in the header and the sidecar directory (`<name>.assets/`).
 *
 * Edges whose address resolves in `registry` are printed against an `import`ed interface; the others get an
 * inline interface declaration (when their ports are known) or a bare `at "address"`. Arrays with more than
 * `maxElements` elements, strings longer than `maxText` characters and multi-line strings longer than 80
 * characters are written to sidecar assets and referenced from the text.
 */
export function printDocument(
  doc: Document,
  options: PrintOptions = {},
): Printed {
  const printer = new Printer(
    options.name ?? "document",
    options.width ?? 100,
    options.maxElements ?? 100,
    options.maxText ?? 1000,
    options.registry,
  );
  return { text: printer.document(doc), assets: printer.assets };
}

/** Print one model declaration (a header or a sort). */
export function printModel(decl: ModelDecl, width = 100): string {
  const printer = new Printer(decl.name, width, 100, 1000, undefined);
  printer.model(decl);
  return printer.lines.join("\n") + "\n";
}

/** Print an interface file (`module …;` plus one declaration per step/process). */
export function printInterfaces(
  decls: InterfaceDecl[],
  moduleName: string,
  width = 100,
): string {
  const printer = new Printer(moduleName, width, 100, 1000, undefined);
  printer.lines = [
    `// pblang v2 interface file - generated by describe from ${moduleName}`,
    `module ${moduleName};`,
  ];
  for (const decl of decls) {
    printer.lines.push("");
    printer.interface(decl, true);
  }
  return printer.lines.join("\n") + "\n";
}

class Printer {
  readonly assets = new Map<string, string>();
  lines: string[] = [];
  private readonly interfaces: InterfaceDecl[] = []; // inline declarations to print
  private readonly interfaceOf = new Map<Edge, InterfaceDecl>();
  private readonly imports = new Map<string, Set<string>>();
  private readonly path: string[] = [];
  private saved = false;
  private declared = new Map<string, InterfaceDecl>();
  private readonly externalized = new Map<unknown, ExternalRef>();

  constructor(
    private readonly name: string,
    private readonly width: number,
    private readonly maxElements: number,
    private readonly maxText: number,
    private readonly registry: Registry | undefined,
  ) {}

  // --- module --------------------------------------------------------------------------------------------------

  document(doc: Document): string {
    this.saved = doc.source === "saved";
    this.declared = new Map(doc.interfaces.map((d) => [d.name, d]));
    this.lines = [`// pblang v2 - printed from ${this.name}`];
    if (doc.module) this.lines.push(`module ${doc.module};`);
    this.collectInterfaces(doc.root);
    if (this.imports.size > 0) {
      this.lines.push("");
      for (const module of [...this.imports.keys()].sort()) {
        const names = [...this.imports.get(module)!].sort().join(", ");
        this.lines.push(`import ${module}.{${names}};`);
      }
    }
    if (doc.params.length > 0) {
      this.lines.push("");
      for (const param of doc.params) this.param(param);
    }
    for (const model of doc.models) {
      this.lines.push("");
      this.model(model);
    }
    if (doc.tags.length > 0 || doc.requires.size > 0 || doc.extras.size > 0) {
      this.lines.push("");
      const meta: Dict = new Map<string, unknown>([
        ["tags", doc.tags],
        ["requires", doc.requires],
        ...doc.extras,
      ]);
      this.block("meta", meta, 0, true);
    }
    if (doc.options.size > 0) {
      this.lines.push("");
      this.block("options", doc.options, 0);
    }
    for (const decl of this.interfaces) {
      this.lines.push("");
      this.interface(decl, true);
    }
    this.lines.push("");
    if (doc.description) this.docComment(doc.description, 0);
    const head = "composite" + (doc.name ? ` ${keyText(doc.name)}` : "");
    this.lines.push(head + " {");
    this.children(doc.root, 1);
    this.lines.push("}");
    if (doc.emitters.length > 0) {
      this.lines.push("");
      for (const emitter of doc.emitters) this.emit(emitter);
    }
    return this.lines.join("\n") + "\n";
  }

  private param(param: Param): void {
    if (param.description) this.docComment(param.description, 0);
    const typeText =
      param.type !== undefined ? surface(param.type) : inferType(param.default);
    let line = `param ${param.name}: ${typeText}`;
    line +=
      param.default !== MISSING
        ? ` = ${this.inline(param.default, 0)}`
        : " = ?";
    if (param.choices !== undefined)
      line += ` choices ${this.inline([...param.choices], 0)}`;
    this.lines.push(line + ";");
  }

  private emit(emitter: Emitter): void {
    const alias =
      emitter.address.protocol === "local"
        ? EMITTER_ALIASES[addressShortName(emitter.address)]
        : undefined;
    const target = alias ?? pyJsonString(addressText(emitter.address));
    const paths = emitter.paths.map(pathToText).join(", ");
    let line = `emit ${target} { ${paths} }`;
    if (emitter.config.size > 0)
      line += " with " + this.inline(emitter.config, 0);
    this.lines.push(line + ";");
  }

  private docComment(text: string, depth: number): void {
    const pad = INDENT.repeat(depth);
    for (const paragraph of text.trim().split("\n")) {
      const wrapped = wrapText(
        paragraph.trimEnd(),
        Math.max(40, this.width - pad.length - 4),
      );
      for (const line of wrapped.length > 0 ? wrapped : [""])
        this.lines.push(`${pad}/// ${line}`);
    }
  }

  // --- interfaces ----------------------------------------------------------------------------------------------

  private collectInterfaces(composite: Composite): void {
    for (const element of composite.children.values()) {
      if (element.$kind === "node")
        this.collectInterfaces({
          children: element.children,
          schemaExtras: new Map(),
        });
      else if (element.$kind === "edge") {
        if (!edgeIsComposite(element)) this.resolveInterface(element);
        if (element.inner !== undefined) this.collectInterfaces(element.inner);
      }
    }
  }

  private resolveInterface(edge: Edge): void {
    let decl =
      edge.ifaceName !== undefined
        ? this.declared.get(edge.ifaceName)
        : undefined;
    if (
      decl === undefined &&
      this.registry !== undefined &&
      isPlainAddress(edge.address)
    )
      decl = this.registry.lookup(addressText(edge.address));
    if (decl !== undefined) {
      this.interfaceOf.set(edge, decl);
      if (decl.module) {
        if (!this.imports.has(decl.module))
          this.imports.set(decl.module, new Set());
        this.imports.get(decl.module)!.add(decl.name);
      } else if (!this.interfaces.includes(decl)) this.interfaces.push(decl);
    } else if (edge.ports !== undefined) {
      this.interfaceOf.set(edge, this.interfaceFor(edge));
    }
  }

  /** An inline declaration derived from the edge's `_inputs`/`_outputs`, shared by edges that agree. */
  private interfaceFor(edge: Edge): InterfaceDecl {
    const ports = edge.ports!;
    const address = isPlainAddress(edge.address) ? edge.address : undefined;
    const base =
      address !== undefined
        ? addressShortName(address)
        : `Interface_${slug(edge.name)}`;
    const kind = edge.kind !== "step" ? "process" : "step";
    const addressString =
      address !== undefined ? addressText(address) : undefined;
    for (const existing of this.interfaces) {
      if (
        existing.kind === kind &&
        existing.address === addressString &&
        sameFace(existing, ports)
      )
        return existing;
    }
    const taken = new Set(this.interfaces.map((i) => i.name));
    for (const names of this.imports.values())
      for (const n of names) taken.add(n);
    let name = base;
    let counter = 2;
    while (taken.has(name)) name = `${base}_${counter++}`;
    const decl: InterfaceDecl = {
      name,
      kind,
      address: addressString,
      config: {},
      dynamicPorts: false,
    };
    if (ports.inputs !== undefined) decl.inputs = ports.inputs;
    if (ports.outputs !== undefined) decl.outputs = ports.outputs;
    this.interfaces.push(decl);
    return decl;
  }

  interface(decl: InterfaceDecl, withAddress = true): void {
    if (decl.doc) this.docComment(decl.doc, 0);
    let head = `${decl.kind} ${decl.name}`;
    if (decl.address !== undefined && withAddress)
      head += ` at ${pyJsonString(decl.address)}`;
    this.lines.push(head + " {");
    const config = Object.entries(decl.config);
    if (config.length > 0)
      this.declarationBlock(
        "config",
        config.map(([k, f]) => this.configField(k, f)),
      );
    if (decl.dynamicPorts)
      this.lines.push(
        `${INDENT}// TODO: dynamic ports: inputs()/outputs() need an instance; declare them by hand`,
      );
    for (const [label, ports] of [
      ["inputs", decl.inputs],
      ["outputs", decl.outputs],
    ] as const) {
      if (ports === undefined) {
        if (decl.dynamicPorts) this.lines.push(`${INDENT}${label} { ... }`);
        continue;
      }
      this.declarationBlock(
        label,
        Object.entries(ports).map(
          ([port, type]) => `${keyText(port)}: ${surface(type)};`,
        ),
      );
    }
    this.lines.push("}");
  }

  model(decl: ModelDecl): void {
    if (decl.doc) this.docComment(decl.doc, 0);
    let head = `model ${keyText(decl.name)}`;
    if (decl.source !== undefined) head += ` from ${pyJsonString(decl.source)}`;
    this.lines.push(head + " {");
    for (const note of decl.notes) this.lines.push(`${INDENT}// note: ${note}`);
    if (decl.timeUnits)
      this.lines.push(`${INDENT}time @ ${pyJsonString(decl.timeUnits)};`);
    const kind = decl.meta.kind;
    for (const label of MODEL_BLOCKS) {
      const fields = Object.entries(decl.blocks[label]);
      if (fields.length === 0 && !decl.openBlocks.has(label)) continue;
      if (label === "species" && kind === "concentration")
        this.lines.push(
          `${INDENT}// concentrations (amount per compartment size)`,
        );
      else if (label === "species" && kind === "amount")
        this.lines.push(
          `${INDENT}// amounts (species with only substance units)`,
        );
      const entries = fields.map(([k, f]) => this.configField(k, f));
      if (decl.openBlocks.has(label)) entries.push("...");
      this.declarationBlock(label, entries);
    }
    if (Object.keys(decl.meta).length > 0)
      this.block("meta", new Map(Object.entries(decl.meta)), 1);
    this.lines.push("}");
  }

  private configField(name: string, field: ConfigField): string {
    let type = field.type;
    let defaultValue: unknown = field.hasDefault ? field.default : MISSING;
    if (type !== undefined && type.kind === "named" && type.hasDefault) {
      if (defaultValue === MISSING) defaultValue = type.default;
      const stripped: Named = {
        kind: "named",
        name: type.name,
        args: type.args,
      };
      if (type.units !== undefined) stripped.units = type.units;
      type = stripped;
    }
    let text = `${keyText(name)}: ${
      type !== undefined ? surface(type) : "node"
    }`;
    if (defaultValue !== MISSING) text += ` = ${this.inline(defaultValue, 1)}`;
    return text + ";";
  }

  private declarationBlock(label: string, entries: string[]): void {
    const inline =
      entries.length > 0
        ? `${INDENT}${label} { ${entries.join(" ")} }`
        : `${INDENT}${label} { }`;
    if (inline.length <= this.width) {
      this.lines.push(inline);
      return;
    }
    this.lines.push(`${INDENT}${label} {`);
    for (const entry of entries) this.lines.push(`${INDENT.repeat(2)}${entry}`);
    this.lines.push(`${INDENT}}`);
  }

  // --- tree ----------------------------------------------------------------------------------------------------

  private children(composite: Composite, depth: number): void {
    const elements = [...composite.children.values()];
    const groups: Element[][] = [
      elements.filter((e) => e.$kind === "store"),
      elements.filter((e) => e.$kind === "node"),
      elements.filter((e) => e.$kind === "edge"),
    ];
    let first = true;
    for (const group of groups) {
      if (group.length === 0) continue;
      if (!first && group.some((e) => e.$kind !== "store")) this.lines.push("");
      first = false;
      for (const element of group) this.element(element, depth);
    }
    if (composite.schemaExtras.size > 0)
      this.block("schema", composite.schemaExtras, depth);
  }

  private element(element: Element, depth: number): void {
    this.path.push(element.name);
    try {
      if (element.$kind === "store") this.store(element, depth);
      else if (element.$kind === "node") this.node(element, depth);
      else this.edge(element, depth);
    } finally {
      this.path.pop();
    }
  }

  private store(store: Store, depth: number): void {
    const pad = INDENT.repeat(depth);
    if (store.doc) this.docComment(store.doc, depth);
    let line = `${pad}store ${keyText(store.name)}`;
    if (store.site !== undefined) {
      const sortText = surface(store.site.sort);
      const typeText =
        store.type !== undefined ? surface(store.type) : sortText;
      line += `: ${typeText} = ?`;
      if (store.site.default !== MISSING)
        line += `(${this.inline(store.site.default, depth)})`;
      if (store.type !== undefined && typeText !== sortText)
        line += ` as ${sortText}`;
      this.lines.push(line + ";");
      return;
    }
    if (store.type !== undefined) line += `: ${surface(store.type)}`;
    if (store.value !== MISSING)
      this.lines.push(this.assign(line + " = ", store.value, depth) + ";");
    else this.lines.push(line + ";");
  }

  private node(node: Node, depth: number): void {
    const pad = INDENT.repeat(depth);
    if (node.doc) this.docComment(node.doc, depth);
    let head = `${pad}node ${keyText(node.name)}`;
    if (node.type !== undefined) head += ` : ${surface(node.type)}`;
    if (node.children.size === 0) {
      this.lines.push(head + " { }");
      return;
    }
    this.lines.push(head + " {");
    this.children(
      { children: node.children, schemaExtras: new Map() },
      depth + 1,
    );
    this.lines.push(`${pad}}`);
  }

  private edge(edge: Edge, depth: number): void {
    const pad = INDENT.repeat(depth);
    if (edge.doc) this.docComment(edge.doc, depth);
    const composite = edgeIsComposite(edge);
    if (
      composite &&
      this.saved &&
      !(edge.inner !== undefined && edge.inner.children.size > 0)
    )
      this.lines.push(
        `${pad}// WARNING: inner state lost by Composite.save (process-bigraph saves nested composites empty)`,
      );
    this.lines.push(`${pad}${this.edgeHead(edge)} {`);
    if (composite) {
      if (edge.bridge !== undefined && edge.bridge.size > 0) {
        const bridge = new Map<string, unknown>();
        for (const [k, v] of edge.bridge)
          bridge.set(k, isDict(v) ? wireFromDocument(v) : v);
        this.wireBlock("bridge", bridge, depth + 1);
      }
      if (edge.interface !== undefined && edge.interface.size > 0)
        this.block("interface", edge.interface, depth + 1);
      if (edge.inner !== undefined) {
        this.lines.push(`${INDENT.repeat(depth + 1)}composite {`);
        this.children(edge.inner, depth + 2);
        this.lines.push(`${INDENT.repeat(depth + 1)}}`);
      }
    }
    if (edge.config.size > 0) this.block("config", edge.config, depth + 1);
    if (edge.inputs.size > 0) this.wireBlock("inputs", edge.inputs, depth + 1);
    if (edge.outputs.size > 0)
      this.wireBlock("outputs", edge.outputs, depth + 1);
    if (edge.ports !== undefined && !composite && this.portsDiffer(edge))
      this.portsBlock(edge.ports, depth + 1);
    if (edge.extras.size > 0) this.block("extra", edge.extras, depth + 1);
    this.lines.push(`${pad}}`);
  }

  private edgeHead(edge: Edge): string {
    const key = keyText(edge.name);
    let head: string;
    if (edgeIsComposite(edge)) head = `composite ${key}`;
    else if (edge.kind === "shared_process")
      head = `shared process ${key} : ${this.edgeType(edge)}`;
    else if (edge.kind === "shared_process_ref")
      head = `process ${key} : shared ${keyText(
        String(edge.extras.get("process_id") ?? "?"),
      )}`;
    else {
      const kind = edge.kind === "step" ? "step" : "process";
      const edgeType = this.edgeType(edge);
      head = edgeType.startsWith("at ")
        ? `${kind} ${key} ${edgeType}`
        : `${kind} ${key} : ${edgeType}`;
    }
    if (edge.interval !== undefined)
      head += ` every ${this.inline(edge.interval, 0)}`;
    if (edge.priority !== undefined)
      head += ` priority ${this.inline(edge.priority, 0)}`;
    return head;
  }

  /** Whether the edge's own `_inputs`/`_outputs` say something its interface declaration does not. */
  private portsDiffer(edge: Edge): boolean {
    const decl = this.interfaceOf.get(edge);
    return (
      decl === undefined ||
      (edge.ports !== undefined && !sameFace(decl, edge.ports))
    );
  }

  private edgeType(edge: Edge): string {
    const decl = this.interfaceOf.get(edge);
    const address = edge.address;
    if (decl !== undefined) {
      let text = decl.name;
      if (
        (decl.address === undefined || !isPlainAddress(address)) &&
        address !== undefined
      )
        text += ` at ${this.addressText(address)}`;
      return text;
    }
    return address !== undefined ? `at ${this.addressText(address)}` : "at ?";
  }

  private addressText(address: Address | Site | ParamRef): string {
    if (isSite(address)) {
      let text = "?";
      if (address.default !== MISSING)
        text += `(${this.inline(address.default, 0)})`;
      return text;
    }
    if (isParamRef(address)) return this.inline(address, 0);
    return pyJsonString(addressText(address));
  }

  private portsBlock(ports: Face, depth: number): void {
    const pad = INDENT.repeat(depth);
    this.lines.push(`${pad}ports {`);
    for (const [label, declared] of [
      ["inputs", ports.inputs],
      ["outputs", ports.outputs],
    ] as const) {
      if (declared === undefined) continue;
      const entries = Object.entries(declared)
        .map(([k, v]) => `${keyText(k)}: ${surface(v)};`)
        .join(" ");
      this.lines.push(
        entries
          ? `${pad}${INDENT}${label} { ${entries} }`
          : `${pad}${INDENT}${label} { }`,
      );
    }
    this.lines.push(`${pad}}`);
  }

  // --- blocks --------------------------------------------------------------------------------------------------

  private block(
    label: string,
    entries: Dict,
    depth: number,
    dropEmpty = false,
  ): void {
    if (dropEmpty) {
      const kept: Dict = new Map();
      for (const [k, v] of entries) if (!isEmptyValue(v)) kept.set(k, v);
      entries = kept;
    }
    const pad = INDENT.repeat(depth);
    if (entries.size === 0) {
      this.lines.push(`${pad}${label} { }`);
      return;
    }
    this.lines.push(this.assign(`${pad}${label} `, entries, depth));
  }

  private wireBlock(
    label: string,
    wires: Map<string, unknown>,
    depth: number,
  ): void {
    const pad = INDENT.repeat(depth);
    const items = [...wires].map(([k, v]) =>
      wireText(
        k,
        Array.isArray(v) || typeof v === "string"
          ? pathFromDocument(v)
          : (v as Wire),
      ),
    );
    const inline = `${pad}${label} { ${items.join(", ")} }`;
    if (inline.length <= this.width) {
      this.lines.push(inline);
      return;
    }
    this.lines.push(`${pad}${label} {`);
    for (const item of items) this.lines.push(`${pad}${INDENT}${item},`);
    this.lines.push(`${pad}}`);
  }

  // --- values --------------------------------------------------------------------------------------------------

  /** `prefix` + value, inline when it fits, otherwise broken over lines at `depth`. */
  private assign(prefix: string, value: unknown, depth: number): string {
    const inline = this.inline(value, depth);
    if (prefix.length + inline.length <= this.width) return prefix + inline;
    return prefix + this.multiline(value, depth);
  }

  private inline(value: unknown, depth: number): string {
    value = this.externalize(value);
    if (isExternalRef(value)) return externalText(value);
    if (isParamRef(value))
      return value.template !== undefined
        ? pyJsonString(value.template)
        : `\${${value.name}}`;
    if (isModelRef(value)) return keyText(value.name);
    if (isSite(value)) return this.siteText(value.sort, value.default, depth);
    if (isSiteDict(value)) {
      const sort = parseType(value.has("_sort") ? value.get("_sort") : "node");
      return this.siteText(
        sort,
        value.has("_default") ? value.get("_default") : MISSING,
        depth,
      );
    }
    if (isNdArray(value))
      return `array(${this.inline(value.data, depth)}, dtype = "${
        value.dtype
      }")`;
    if (isDict(value)) {
      if (value.size === 0) return "{}";
      const struct = [...value.keys()].every(isIdentifier);
      const items = [...value].map(
        ([k, v]) =>
          `${struct ? k : pyJsonString(k)} = ${this.inlineAt(k, v, depth)}`,
      );
      return "{ " + items.join(", ") + " }";
    }
    if (isTuple(value))
      return (
        "(" + value.items.map((v) => this.inline(v, depth)).join(", ") + ")"
      );
    if (Array.isArray(value))
      return "[" + value.map((v) => this.inline(v, depth)).join(", ") + "]";
    return scalarText(value);
  }

  /** `inline`, with `key` on the path so that an externalized value is named after where it sits. */
  private inlineAt(key: string, value: unknown, depth: number): string {
    this.path.push(key);
    try {
      return this.inline(value, depth);
    } finally {
      this.path.pop();
    }
  }

  private multiline(value: unknown, depth: number): string {
    value = this.externalize(value);
    const pad = INDENT.repeat(depth + 1);
    const end = INDENT.repeat(depth);
    if (isNdArray(value))
      return `array(${this.multiline(value.data, depth)}, dtype = "${
        value.dtype
      }")`;
    if (isDict(value) && value.size > 0) {
      const struct = [...value.keys()].every(isIdentifier);
      const lines: string[] = [];
      for (const [key, item] of value) {
        const label = struct ? key : pyJsonString(key);
        this.path.push(key);
        try {
          lines.push(this.assign(`${pad}${label} = `, item, depth + 1) + ",");
        } finally {
          this.path.pop();
        }
      }
      return "{\n" + lines.join("\n") + `\n${end}}`;
    }
    const items = isTuple(value)
      ? value.items
      : Array.isArray(value)
      ? value
      : undefined;
    if (items !== undefined && items.length > 0) {
      const [open, close] = isTuple(value) ? ["(", ")"] : ["[", "]"];
      const lines = items.map(
        (item) => this.assign(pad, item, depth + 1) + ",",
      );
      return `${open}\n` + lines.join("\n") + `\n${end}${close}`;
    }
    return this.inline(value, depth);
  }

  private siteText(
    sort: TypeExpr,
    defaultValue: unknown,
    depth: number,
  ): string {
    let text = "?";
    if (defaultValue !== MISSING)
      text += `(${this.inline(defaultValue, depth)})`;
    return `${text} as ${surface(sort)}`;
  }

  /** Replace a large array or text by a sidecar asset reference (once per value: layout may retry). */
  private externalize(value: unknown): unknown {
    const memo = this.externalized.get(value);
    if (memo !== undefined) return memo;
    let ref: ExternalRef | undefined;
    if (isNdArray(value) && elementCount(value) > this.maxElements) {
      const name = `${this.assetPrefix()}.json`;
      const payload = new Map<string, unknown>([
        ["dtype", value.dtype],
        ["shape", value.shape.map((s) => BigInt(s))],
        ["data", value.data],
      ]);
      this.assets.set(name, pyJsonDumps(payload) + "\n");
      ref = {
        $kind: "external",
        path: name,
        format: "array",
        dtype: value.dtype,
        shape: [...value.shape],
      };
    } else if (
      (Array.isArray(value) || isTuple(value)) &&
      elementCount(value) > this.maxElements &&
      isNumericTree(value)
    ) {
      const name = `${this.assetPrefix()}.json`;
      this.assets.set(name, pyJsonDumps(value) + "\n");
      ref = { $kind: "external", path: name, format: "json" };
    } else if (
      typeof value === "string" &&
      (value.length > this.maxText ||
        (value.includes("\n") && value.length > 80))
    ) {
      const name = `${this.assetPrefix()}.txt`;
      this.assets.set(name, value);
      ref = { $kind: "external", path: name, format: "text" };
    }
    if (ref === undefined) return value;
    this.externalized.set(value, ref);
    return ref;
  }

  private assetPrefix(): string {
    const base = `${this.name}.assets/${slug(this.path.join("_") || "value")}`;
    let candidate = base;
    let counter = 2;
    const taken = (c: string) =>
      [...this.assets.keys()].some((k) => k.startsWith(c + "."));
    while (taken(candidate)) candidate = `${base}_${counter++}`;
    return candidate;
  }
}

// --- helpers -----------------------------------------------------------------------------------------------------

function wireText(port: string, wire: Wire): string {
  if (wire instanceof Map) {
    const inner = [...wire].map(([k, v]) => wireText(k, v)).join(", ");
    return `${keyText(port)} { ${inner} }`;
  }
  return `${keyText(port)} -> ${pathToText(wire)}`;
}

function externalText(ref: ExternalRef): string {
  if (ref.format === "array")
    return `array(file(${pyJsonString(ref.path)}), dtype = "${
      ref.dtype
    }", shape = [${(ref.shape ?? []).join(", ")}])`;
  return `file(${pyJsonString(ref.path)})`;
}

export function scalarText(value: unknown): string {
  if (value === null || value === undefined) return "null";
  if (typeof value === "boolean") return value ? "true" : "false";
  if (typeof value === "bigint") return value.toString();
  if (typeof value === "number") return floatLiteral(value);
  if (typeof value === "string") return pyJsonString(value);
  return pyJsonString(String(value));
}

export function keyText(key: string): string {
  return isIdentifier(key) ? key : pyJsonString(key);
}

function slug(text: string): string {
  return (
    [...text]
      .map((c) => (/[\p{L}\p{N}_]/u.test(c) ? c : "_"))
      .join("")
      .replace(/^_+|_+$/g, "") || "value"
  );
}

function inferType(value: unknown): string {
  if (typeof value === "boolean") return "bool";
  if (typeof value === "bigint") return "int";
  if (typeof value === "number") return "float";
  if (typeof value === "string") return "string";
  if (Array.isArray(value) || isTuple(value)) return "list<node>";
  if (isDict(value)) return "map<string, node>";
  return "node";
}

function isNumericTree(value: unknown): boolean {
  if (Array.isArray(value)) return value.every(isNumericTree);
  if (isTuple(value)) return value.items.every(isNumericTree);
  return typeof value === "number" || typeof value === "bigint";
}

function isEmptyValue(value: unknown): boolean {
  return (
    value === null ||
    value === undefined ||
    value === "" ||
    (Array.isArray(value) && value.length === 0) ||
    (isDict(value) && value.size === 0)
  );
}

function isPlainAddress(
  address: Address | Site | ParamRef | undefined,
): address is Address {
  return address !== undefined && !isSite(address) && !isParamRef(address);
}

/** Undeclared ports and an empty declaration say the same thing. */
function sameFace(a: Face, b: Face): boolean {
  return (
    portsText(a.inputs) === portsText(b.inputs) &&
    portsText(a.outputs) === portsText(b.outputs)
  );
}

function portsText(ports: Record<string, TypeExpr> | undefined): string {
  const entries = Object.entries(ports ?? {}).sort(([a], [b]) =>
    a < b ? -1 : a > b ? 1 : 0,
  );
  return JSON.stringify(
    Object.fromEntries(entries.map(([k, v]) => [k, surface(v)])),
  );
}

/** Python's `json.dumps(value)` with its default separators and float spelling. */
export function pyJsonDumps(value: unknown): string {
  if (value === null || value === undefined) return "null";
  if (typeof value === "boolean") return value ? "true" : "false";
  if (typeof value === "bigint") return value.toString();
  if (typeof value === "number") {
    if (Number.isNaN(value)) return "NaN";
    if (!Number.isFinite(value)) return value > 0 ? "Infinity" : "-Infinity";
    return pyFloatRepr(value);
  }
  if (typeof value === "string") return pyJsonString(value);
  if (isTuple(value)) return pyJsonDumps(value.items);
  if (isNdArray(value)) return pyJsonDumps(value.data);
  if (Array.isArray(value)) return `[${value.map(pyJsonDumps).join(", ")}]`;
  if (isDict(value))
    return `{${[...value]
      .map(([k, v]) => `${pyJsonString(k)}: ${pyJsonDumps(v)}`)
      .join(", ")}}`;
  if (typeof value === "object")
    return `{${Object.entries(value as Record<string, unknown>)
      .map(([k, v]) => `${pyJsonString(k)}: ${pyJsonDumps(v)}`)
      .join(", ")}}`;
  return pyJsonString(String(value));
}
