"""
The v2 model -> canonical `.pblang` v2 text.

The printer is deterministic: it orders stores, then nodes, then edges (each in source order), prints a block
inline when it fits in `width` columns and one entry per line otherwise, and externalizes large arrays and
texts into sidecar assets (`array(file("…"))`, `file("…")`) so the text stays reviewable. There is no v2 parser
yet, so the text is for human review and for seeding the Langium v2 grammar.

Internal: `api.decompile` is the public entry.
"""

from __future__ import annotations

import json
import textwrap
from dataclasses import dataclass, field
from typing import Any

import numpy as np

from process_bigraph_lang.v2.interfaces import InterfaceRegistry
from process_bigraph_lang.v2.model import (
    Address,
    Composite,
    ConfigField,
    Document,
    Edge,
    Element,
    Emitter,
    ExternalRef,
    Face,
    InterfaceDecl,
    MODEL_BLOCKS,
    ModelDecl,
    ModelRef,
    Node,
    Param,
    ParamRef,
    Site,
    Store,
)
from process_bigraph_lang.v2.paths import Path, Wire, wire_from_document
from process_bigraph_lang.v2.types import Named, TypeExpr, parse_type, to_surface
from process_bigraph_lang.v2.values import MISSING, element_count, is_identifier, is_site

EMITTER_ALIASES = {
    "RAMEmitter": "ram",
    "ParquetEmitter": "parquet",
    "SQLiteEmitter": "sqlite",
    "XarrayEmitter": "xarray",
    "ConsoleEmitter": "console",
    "JSONEmitter": "json",
}
INDENT = "  "


@dataclass
class Printed:
    text: str
    assets: dict[str, bytes] = field(default_factory=dict)


def print_document(
    doc: Document,
    *,
    name: str = "document",
    registry: InterfaceRegistry | None = None,
    width: int = 100,
    max_elements: int = 100,
    max_text: int = 1000,
) -> Printed:
    """
    Print a module. `name` names the source in the header and the sidecar directory (`<name>.assets/`).

    Edges whose address resolves in `registry` are printed against an `import`ed interface; the others get an
    inline interface declaration (when their ports are known) or a bare `at "address"`. Arrays with more than
    `max_elements` elements, strings longer than `max_text` characters and multi-line strings longer than 80
    characters are written to sidecar assets and referenced from the text.
    """
    printer = _Printer(name, width, max_elements, max_text, registry)
    return Printed(printer.document(doc), printer.assets)


def print_model(decl: ModelDecl, *, width: int = 100) -> str:
    """Print one model declaration (a header or a sort)."""
    printer = _Printer(decl.name, width, 100, 1000, None)
    printer.model(decl)
    return "\n".join(printer.lines) + "\n"


def print_interfaces(decls: list[InterfaceDecl], module_name: str, *, width: int = 100) -> str:
    """Print an interface file (`module …;` plus one declaration per step/process)."""
    printer = _Printer(module_name, width, 100, 1000, None)
    printer.lines = [
        f"// pblang v2 interface file - generated by describe from {module_name}",
        f"module {module_name};",
    ]
    for decl in decls:
        printer.lines.append("")
        printer.interface(decl, with_address=True)
    return "\n".join(printer.lines) + "\n"


class _Printer:
    def __init__(
        self, name: str, width: int, max_elements: int, max_text: int, registry: InterfaceRegistry | None
    ) -> None:
        self.name = name
        self.width = width
        self.max_elements = max_elements
        self.max_text = max_text
        self.registry = registry
        self.assets: dict[str, bytes] = {}
        self.interfaces: list[InterfaceDecl] = []  # inline declarations to print
        self.interface_of: dict[int, InterfaceDecl] = {}
        self.imports: dict[str, set[str]] = {}
        self.lines: list[str] = []
        self.path: list[str] = []
        self.saved = False
        self.declared: dict[str, InterfaceDecl] = {}
        self.externalized: dict[int, ExternalRef] = {}
        self.keep_alive: list[Any] = []

    # --- module --------------------------------------------------------------------------------------------------

    def document(self, doc: Document) -> str:
        self.saved = doc.source == "saved"
        self.declared = {d.name: d for d in doc.interfaces}
        self.lines = [f"// pblang v2 - printed from {self.name}"]
        if doc.module:
            self.lines.append(f"module {doc.module};")
        self.collect_interfaces(doc.root)
        if self.imports:
            self.lines.append("")
            for module in sorted(self.imports):
                names = ", ".join(sorted(self.imports[module]))
                self.lines.append(f"import {module}.{{{names}}};")
        if doc.params:
            self.lines.append("")
            for param in doc.params:
                self.param(param)
        for model in doc.models:
            self.lines.append("")
            self.model(model)
        if doc.tags or doc.requires or doc.extras:
            self.lines.append("")
            self.block("meta", {"tags": doc.tags, "requires": doc.requires, **doc.extras}, 0, drop_empty=True)
        if doc.options:
            self.lines.append("")
            self.block("options", doc.options, 0)
        for interface in self.interfaces:
            self.lines.append("")
            self.interface(interface)
        self.lines.append("")
        if doc.description:
            self.doc_comment(doc.description, 0)
        head = "composite" + (f" {_key(doc.name)}" if doc.name else "")
        self.lines.append(head + " {")
        self.children(doc.root, 1)
        self.lines.append("}")
        if doc.emitters:
            self.lines.append("")
            for emitter in doc.emitters:
                self.emit(emitter)
        return "\n".join(self.lines) + "\n"

    def param(self, param: Param) -> None:
        if param.description:
            self.doc_comment(param.description, 0)
        type_text = to_surface(param.type) if param.type is not None else _infer_type(param.default)
        line = f"param {param.name}: {type_text}"
        line += f" = {self.inline(param.default, 0)}" if param.default is not MISSING else " = ?"
        if param.choices is not None:
            line += f" choices {self.inline(list(param.choices), 0)}"
        self.lines.append(line + ";")

    def emit(self, emitter: Emitter) -> None:
        alias = EMITTER_ALIASES.get(emitter.address.short_name) if emitter.address.protocol == "local" else None
        target = alias or json.dumps(str(emitter.address))
        paths = ", ".join(p.to_text() for p in emitter.paths)
        line = f"emit {target} {{ {paths} }}"
        if emitter.config:
            line += " with " + self.inline(emitter.config, 0)
        self.lines.append(line + ";")

    def doc_comment(self, text: str, depth: int) -> None:
        pad = INDENT * depth
        for paragraph in text.strip().splitlines():
            wrapped = textwrap.wrap(paragraph.rstrip(), width=max(40, self.width - len(pad) - 4)) or [""]
            self.lines.extend(f"{pad}/// {line}" for line in wrapped)

    # --- interfaces ----------------------------------------------------------------------------------------------

    def collect_interfaces(self, composite: Composite) -> None:
        for element in composite.children.values():
            if isinstance(element, Node):
                self.collect_interfaces(Composite(element.children))
            elif isinstance(element, Edge):
                if not element.is_composite:
                    self.resolve_interface(element)
                if element.inner is not None:
                    self.collect_interfaces(element.inner)

    def resolve_interface(self, edge: Edge) -> None:
        decl = self.declared.get(edge.iface_name) if edge.iface_name else None
        if decl is None and self.registry is not None and isinstance(edge.address, Address):
            decl = self.registry.lookup(edge.address)
        if decl is not None:
            self.interface_of[id(edge)] = decl
            if decl.module:
                self.imports.setdefault(decl.module, set()).add(decl.name)
            elif decl not in self.interfaces:
                self.interfaces.append(decl)
        elif edge.ports is not None:
            self.interface_of[id(edge)] = self.interface_for(edge)

    def interface_for(self, edge: Edge) -> InterfaceDecl:
        """An inline declaration derived from the edge's `_inputs`/`_outputs`, shared by edges that agree."""
        assert edge.ports is not None
        address = edge.address if isinstance(edge.address, Address) else None
        base = address.short_name if address is not None else f"Interface_{_slug(edge.name)}"
        kind = "process" if edge.kind != "step" else "step"
        for existing in self.interfaces:
            if (
                existing.kind == kind
                and _same_address(existing.address, address)
                and _same_face(existing.face, edge.ports)
            ):
                return existing
        taken = {i.name for i in self.interfaces} | {n for names in self.imports.values() for n in names}
        name, counter = base, 2
        while name in taken:
            name, counter = f"{base}_{counter}", counter + 1
        decl = InterfaceDecl(name, kind, address, inputs=edge.ports.inputs, outputs=edge.ports.outputs)
        self.interfaces.append(decl)
        return decl

    def interface(self, decl: InterfaceDecl, *, with_address: bool = True) -> None:
        if decl.doc:
            self.doc_comment(decl.doc, 0)
        head = f"{decl.kind} {decl.name}"
        if decl.address is not None and with_address:
            head += f" at {json.dumps(str(decl.address))}"
        self.lines.append(head + " {")
        if decl.config:
            entries = [self.config_field(k, f) for k, f in decl.config.items()]
            self.declaration_block("config", entries)
        if decl.dynamic_ports:
            self.lines.append(
                f"{INDENT}// TODO: dynamic ports: inputs()/outputs() need an instance; declare them by hand"
            )
        for label, ports in (("inputs", decl.inputs), ("outputs", decl.outputs)):
            if ports is None:
                if decl.dynamic_ports:
                    self.lines.append(f"{INDENT}{label} {{ ... }}")
                continue
            entries = [f"{_key(port)}: {to_surface(port_type)};" for port, port_type in ports.items()]
            self.declaration_block(label, entries)
        self.lines.append("}")

    def model(self, decl: ModelDecl) -> None:
        if decl.doc:
            self.doc_comment(decl.doc, 0)
        head = f"model {_key(decl.name)}"
        if decl.source is not None:
            head += f" from {json.dumps(decl.source)}"
        self.lines.append(head + " {")
        for note in decl.notes:
            self.lines.append(f"{INDENT}// note: {note}")
        if decl.time_units:
            self.lines.append(f"{INDENT}time @ {json.dumps(decl.time_units)};")
        kind = decl.meta.get("kind")
        for label in MODEL_BLOCKS:
            fields = decl.block(label)
            if not fields and label not in decl.open_blocks:
                continue
            if label == "species" and kind == "concentration":
                self.lines.append(f"{INDENT}// concentrations (amount per compartment size)")
            elif label == "species" and kind == "amount":
                self.lines.append(f"{INDENT}// amounts (species with only substance units)")
            entries = [self.config_field(k, f) for k, f in fields.items()]
            if label in decl.open_blocks:
                entries.append("...")
            self.declaration_block(label, entries)
        if decl.meta:
            self.block("meta", decl.meta, 1)
        self.lines.append("}")

    def config_field(self, name: str, config_field: ConfigField) -> str:
        field_type = config_field.type
        default = config_field.default
        if isinstance(field_type, Named) and field_type.default is not MISSING:
            if default is MISSING:
                default = field_type.default
            field_type = Named(field_type.name, field_type.args, units=field_type.units)
        text = f"{_key(name)}: {to_surface(field_type) if field_type is not None else 'node'}"
        if default is not MISSING:
            text += f" = {self.inline(default, 1)}"
        return text + ";"

    def declaration_block(self, label: str, entries: list[str]) -> None:
        inline = f"{INDENT}{label} {{ {' '.join(entries)} }}" if entries else f"{INDENT}{label} {{ }}"
        if len(inline) <= self.width:
            self.lines.append(inline)
            return
        self.lines.append(f"{INDENT}{label} {{")
        self.lines.extend(f"{INDENT * 2}{entry}" for entry in entries)
        self.lines.append(f"{INDENT}}}")

    # --- tree ----------------------------------------------------------------------------------------------------

    def children(self, composite: Composite, depth: int) -> None:
        elements = list(composite.children.values())
        groups = (
            [e for e in elements if isinstance(e, Store)],
            [e for e in elements if isinstance(e, Node)],
            [e for e in elements if isinstance(e, Edge)],
        )
        first = True
        for group in groups:
            if not group:
                continue
            if not first and any(isinstance(e, (Node, Edge)) for e in group):
                self.lines.append("")
            first = False
            for element in group:
                self.element(element, depth)
        if composite.schema_extras:
            self.block("schema", composite.schema_extras, depth)

    def element(self, element: Element, depth: int) -> None:
        self.path.append(element.name)
        try:
            if isinstance(element, Store):
                self.store(element, depth)
            elif isinstance(element, Node):
                self.node(element, depth)
            else:
                self.edge(element, depth)
        finally:
            self.path.pop()

    def store(self, store: Store, depth: int) -> None:
        pad = INDENT * depth
        if store.doc:
            self.doc_comment(store.doc, depth)
        line = f"{pad}store {_key(store.name)}"
        if store.site is not None:
            sort_text = to_surface(store.site.sort)
            type_text = to_surface(store.type) if store.type is not None else sort_text
            line += f": {type_text} = ?"
            if store.site.default is not MISSING:
                line += f"({self.inline(store.site.default, depth)})"
            if store.type is not None and type_text != sort_text:
                line += f" as {sort_text}"
            self.lines.append(line + ";")
            return
        if store.type is not None:
            line += f": {to_surface(store.type)}"
        if store.value is not MISSING:
            self.lines.append(self.assign(line + " = ", store.value, depth) + ";")
        else:
            self.lines.append(line + ";")

    def node(self, node: Node, depth: int) -> None:
        pad = INDENT * depth
        if node.doc:
            self.doc_comment(node.doc, depth)
        head = f"{pad}node {_key(node.name)}"
        if node.type is not None:
            head += f" : {to_surface(node.type)}"
        if not node.children:
            self.lines.append(head + " { }")
            return
        self.lines.append(head + " {")
        self.children(Composite(node.children), depth + 1)
        self.lines.append(f"{pad}}}")

    def edge(self, edge: Edge, depth: int) -> None:
        pad = INDENT * depth
        if edge.doc:
            self.doc_comment(edge.doc, depth)
        if edge.is_composite and self.saved and not (edge.inner and edge.inner.children):
            self.lines.append(
                f"{pad}// WARNING: inner state lost by Composite.save (process-bigraph saves nested composites empty)"
            )
        self.lines.append(f"{pad}{self.edge_head(edge)} {{")
        if edge.is_composite:
            if edge.bridge:
                bridge = {str(k): wire_from_document(v) if isinstance(v, dict) else v for k, v in edge.bridge.items()}
                self.wire_block("bridge", bridge, depth + 1)
            if edge.interface:
                self.block("interface", edge.interface, depth + 1)
            if edge.inner is not None:
                self.lines.append(f"{INDENT * (depth + 1)}composite {{")
                self.children(edge.inner, depth + 2)
                self.lines.append(f"{INDENT * (depth + 1)}}}")
        if edge.config:
            self.block("config", edge.config, depth + 1)
        if edge.inputs:
            self.wire_block("inputs", edge.inputs, depth + 1)
        if edge.outputs:
            self.wire_block("outputs", edge.outputs, depth + 1)
        if edge.ports is not None and not edge.is_composite and self.ports_differ(edge):
            self.ports_block(edge.ports, depth + 1)
        if edge.extras:
            self.block("extra", edge.extras, depth + 1)
        self.lines.append(f"{pad}}}")

    def edge_head(self, edge: Edge) -> str:
        key = _key(edge.name)
        if edge.is_composite:
            head = f"composite {key}"
        elif edge.kind == "shared_process":
            head = f"shared process {key} : {self.edge_type(edge)}"
        elif edge.kind == "shared_process_ref":
            head = f"process {key} : shared {_key(str(edge.extras.get('process_id', '?')))}"
        else:
            kind = "step" if edge.kind == "step" else "process"
            edge_type = self.edge_type(edge)
            head = f"{kind} {key} {edge_type}" if edge_type.startswith("at ") else f"{kind} {key} : {edge_type}"
        if edge.interval is not None:
            head += f" every {self.inline(edge.interval, 0)}"
        if edge.priority is not None:
            head += f" priority {self.inline(edge.priority, 0)}"
        return head

    def ports_differ(self, edge: Edge) -> bool:
        """Whether the edge's own `_inputs`/`_outputs` say something its interface declaration does not."""
        decl = self.interface_of.get(id(edge))
        return decl is None or (edge.ports is not None and not _same_face(decl.face, edge.ports))

    def edge_type(self, edge: Edge) -> str:
        decl = self.interface_of.get(id(edge))
        address = edge.address
        if decl is not None:
            text = decl.name
            if (decl.address is None or not isinstance(address, Address)) and address is not None:
                text += f" at {self.address_text(address)}"
            return text
        return f"at {self.address_text(address)}" if address is not None else "at ?"

    def address_text(self, address: Address | Site | ParamRef) -> str:
        if isinstance(address, Site):
            text = "?"
            if address.default is not MISSING:
                text += f"({self.inline(address.default, 0)})"
            return text
        if isinstance(address, ParamRef):
            return self.inline(address, 0)
        return json.dumps(str(address))

    def ports_block(self, ports: Face, depth: int) -> None:
        pad = INDENT * depth
        self.lines.append(f"{pad}ports {{")
        for label, declared in (("inputs", ports.inputs), ("outputs", ports.outputs)):
            if declared is None:
                continue
            entries = " ".join(f"{_key(k)}: {to_surface(v)};" for k, v in declared.items())
            self.lines.append(f"{pad}{INDENT}{label} {{ {entries} }}" if entries else f"{pad}{INDENT}{label} {{ }}")
        self.lines.append(f"{pad}}}")

    # --- blocks --------------------------------------------------------------------------------------------------

    def block(self, label: str, entries: dict[str, Any], depth: int, *, drop_empty: bool = False) -> None:
        if drop_empty:
            entries = {k: v for k, v in entries.items() if v not in ({}, [], None, "")}
        pad = INDENT * depth
        if not entries:
            self.lines.append(f"{pad}{label} {{ }}")
            return
        self.lines.append(self.assign(f"{pad}{label} ", entries, depth, braces=True))

    def wire_block(self, label: str, wires: dict[str, Any], depth: int) -> None:
        pad = INDENT * depth
        items = [
            _wire_text(k, v) if not isinstance(v, (list, str)) else _wire_text(k, Path.from_document(v))
            for k, v in wires.items()
        ]
        inline = f"{pad}{label} {{ {', '.join(items)} }}"
        if len(inline) <= self.width:
            self.lines.append(inline)
            return
        self.lines.append(f"{pad}{label} {{")
        self.lines.extend(f"{pad}{INDENT}{item}," for item in items)
        self.lines.append(f"{pad}}}")

    # --- values --------------------------------------------------------------------------------------------------

    def assign(self, prefix: str, value: Any, depth: int, *, braces: bool = False) -> str:
        """`prefix` + value, inline when it fits, otherwise broken over lines at `depth`."""
        inline = self.inline(value, depth)
        if len(prefix) + len(inline) <= self.width:
            return prefix + inline
        return prefix + self.multiline(value, depth)

    def inline(self, value: Any, depth: int) -> str:
        value = self.externalize(value)
        if isinstance(value, ExternalRef):
            return _external_text(value)
        if isinstance(value, ParamRef):
            return json.dumps(value.template) if value.template is not None else "${" + value.name + "}"
        if isinstance(value, ModelRef):
            return _key(value.name)
        if isinstance(value, Site):
            return self.site_text(value.sort, value.default, depth)
        if is_site(value):
            sort = parse_type(value.get("_sort", "node"))
            return self.site_text(sort, value.get("_default", MISSING), depth)
        if isinstance(value, np.ndarray):
            return f'array({self.inline(value.tolist(), depth)}, dtype = "{value.dtype}")'
        if isinstance(value, dict):
            if not value:
                return "{}"
            struct = all(is_identifier(k) for k in value)
            items = [f"{k if struct else json.dumps(str(k))} = {self.inline_at(k, v, depth)}" for k, v in value.items()]
            return "{ " + ", ".join(items) + " }"
        if isinstance(value, tuple):
            return "(" + ", ".join(self.inline(v, depth) for v in value) + ")"
        if isinstance(value, list):
            return "[" + ", ".join(self.inline(v, depth) for v in value) + "]"
        return _scalar(value)

    def inline_at(self, key: str, value: Any, depth: int) -> str:
        """`inline`, with `key` on the path so that an externalized value is named after where it sits."""
        self.path.append(str(key))
        try:
            return self.inline(value, depth)
        finally:
            self.path.pop()

    def multiline(self, value: Any, depth: int) -> str:
        value = self.externalize(value)
        pad = INDENT * (depth + 1)
        end = INDENT * depth
        if isinstance(value, np.ndarray):
            return f'array({self.multiline(value.tolist(), depth)}, dtype = "{value.dtype}")'
        if isinstance(value, dict) and value:
            struct = all(is_identifier(k) for k in value)
            lines = []
            for key, item in value.items():
                label = key if struct else json.dumps(str(key))
                self.path.append(str(key))
                try:
                    lines.append(self.assign(f"{pad}{label} = ", item, depth + 1) + ",")
                finally:
                    self.path.pop()
            return "{\n" + "\n".join(lines) + f"\n{end}}}"
        if isinstance(value, (list, tuple)) and value:
            open_, close = ("(", ")") if isinstance(value, tuple) else ("[", "]")
            lines = [self.assign(pad, item, depth + 1) + "," for item in value]
            return f"{open_}\n" + "\n".join(lines) + f"\n{end}{close}"
        return self.inline(value, depth)

    def site_text(self, sort: TypeExpr, default: Any, depth: int) -> str:
        text = "?"
        if default is not MISSING:
            text += f"({self.inline(default, depth)})"
        return f"{text} as {to_surface(sort)}"

    def externalize(self, value: Any) -> Any:
        """Replace a large array or text by a sidecar asset reference (once per value: layout may retry)."""
        if id(value) in self.externalized:
            return self.externalized[id(value)]
        ref: ExternalRef | None = None
        if isinstance(value, np.ndarray) and value.size > self.max_elements:
            name = f"{self.asset_prefix()}.json"
            payload = {"dtype": str(value.dtype), "shape": list(value.shape), "data": value.tolist()}
            self.assets[name] = (json.dumps(payload) + "\n").encode()
            ref = ExternalRef(name, "array", dtype=str(value.dtype), shape=tuple(value.shape))
        elif isinstance(value, list) and element_count(value) > self.max_elements and _is_numeric_tree(value):
            name = f"{self.asset_prefix()}.json"
            self.assets[name] = (json.dumps(value) + "\n").encode()
            ref = ExternalRef(name, "json")
        elif isinstance(value, str) and (len(value) > self.max_text or ("\n" in value and len(value) > 80)):
            name = f"{self.asset_prefix()}.txt"
            self.assets[name] = value.encode()
            ref = ExternalRef(name, "text")
        if ref is None:
            return value
        self.externalized[id(value)] = ref
        self.keep_alive.append(value)  # so that id(value) stays unique while printing
        return ref

    def asset_prefix(self) -> str:
        base = f"{self.name}.assets/{_slug('_'.join(self.path) or 'value')}"
        candidate, counter = base, 2
        while any(k.startswith(candidate + ".") for k in self.assets):
            candidate, counter = f"{base}_{counter}", counter + 1
        return candidate


# --- helpers -----------------------------------------------------------------------------------------------------


def _wire_text(port: str, wire: Wire) -> str:
    if isinstance(wire, dict):
        inner = ", ".join(_wire_text(k, v) for k, v in wire.items())
        return f"{_key(port)} {{ {inner} }}"
    return f"{_key(port)} -> {wire.to_text()}"


def _external_text(ref: ExternalRef) -> str:
    if ref.kind == "array":
        return f'array(file({json.dumps(ref.path)}), dtype = "{ref.dtype}", shape = {list(ref.shape or ())})'
    return f"file({json.dumps(ref.path)})"


def _scalar(value: Any) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, np.integer)):
        return str(int(value))
    if isinstance(value, (float, np.floating)):
        return _float(float(value))
    if isinstance(value, str):
        return json.dumps(value)
    return json.dumps(str(value))


def _float(value: float) -> str:
    text = repr(float(value))
    if "e" in text or "E" in text:
        mantissa, exponent = text.lower().split("e")
        if "." not in mantissa:
            mantissa += ".0"
        return f"{mantissa}e{exponent}"
    return text


def _key(key: str) -> str:
    return key if is_identifier(key) else json.dumps(key)


def _slug(text: str) -> str:
    return "".join(c if c.isalnum() or c == "_" else "_" for c in text).strip("_") or "value"


def _infer_type(value: Any) -> str:
    if isinstance(value, bool):
        return "bool"
    if isinstance(value, int):
        return "int"
    if isinstance(value, float):
        return "float"
    if isinstance(value, str):
        return "string"
    if isinstance(value, (list, tuple)):
        return "list<node>"
    if isinstance(value, dict):
        return "map<string, node>"
    return "node"


def _is_numeric_tree(value: Any) -> bool:
    if isinstance(value, (list, tuple)):
        return all(_is_numeric_tree(v) for v in value)
    return isinstance(value, (int, float, np.integer, np.floating)) and not isinstance(value, bool)


def _same_address(a: Address | None, b: Address | None) -> bool:
    return (a is None and b is None) or (a is not None and b is not None and str(a) == str(b))


def _same_face(a: Face, b: Face) -> bool:
    """Undeclared ports and an empty declaration say the same thing."""
    return _ports_text(a.inputs) == _ports_text(b.inputs) and _ports_text(a.outputs) == _ports_text(b.outputs)


def _ports_text(ports: dict[str, TypeExpr] | None) -> str:
    return json.dumps({k: to_surface(v) for k, v in (ports or {}).items()}, sort_keys=True)
